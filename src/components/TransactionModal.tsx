type SplitMode = 'ratio' | 'amount'

interface SplitRow {
  id: string
  target: string
  value: string
}

interface SplitResult {
  allocations: AllocationLine[]
  error: string
}

function sanitizeAmount(value: string): string {
  const normalized = value.replace(/,/g, '').replace(/，/g, '.')
  const stripped = normalized.replace(/[^\d.]/g, '')
  const [whole = '', ...rest] = stripped.split('.')
  const decimals = rest.join('').slice(0, 2)
  if (stripped.includes('.')) return `${whole}.${decimals}`
  return whole
}

function parseDecimal(value: string): number {
  const parsed = Number(value)
  return Number.isFinite(parsed) ? parsed : 0
}

function centsToInput(cents: number): string {
  return (cents / 100)
    .toFixed(2)
    .replace(/\.00$/, '')
    .replace(/(\.\d)0$/, '$1')
}

function targetKey(line: AllocationLine): string {
  return line.targetType === 'project' && line.projectId
    ? `project:${line.projectId}`
    : 'daily'
}

function createDefaultSplitRows(
  projects: Project[],
  mode: SplitMode,
  totalCents: number,
): SplitRow[] {
  const project =
    projects.find((item) => item.status === 'active') ?? projects[0]
  if (!project) {
    return [{ id: newAllocationId(), target: 'daily', value: '100' }]
  }

  if (mode === 'ratio') {
    return [
      { id: newAllocationId(), target: 'daily', value: '50' },
      {
        id: newAllocationId(),
        target: `project:${project.id}`,
        value: '50',
      },
    ]
  }

  const dailyCents =
    totalCents > 0 ? Math.floor(totalCents / 2) : 0
  return [
    {
      id: newAllocationId(),
      target: 'daily',
      value: totalCents > 0 ? centsToInput(dailyCents) : '',
    },
    {
      id: newAllocationId(),
      target: `project:${project.id}`,
      value: totalCents > 0 ? centsToInput(totalCents - dailyCents) : '',
    },
  ]
}

function buildSplitAllocations(
  rows: SplitRow[],
  mode: SplitMode,
  totalCents: number,
  projects: Project[],
): SplitResult {
  if (!Number.isFinite(totalCents) || totalCents <= 0) {
    return { allocations: [], error: '请先填写总额' }
  }

  const usable = rows.filter((row) => parseDecimal(row.value) > 0)
  if (usable.length === 0) {
    return { allocations: [], error: '请至少填写一条分摊' }
  }
  if (new Set(usable.map((row) => row.target)).size < 2) {
    return { allocations: [], error: '共用支出至少需要两个不同的归属' }
  }

  const projectIds = new Set(projects.map((project) => project.id))
  for (const row of usable) {
    if (
      row.target !== 'daily' &&
      !projectIds.has(row.target.slice('project:'.length))
    ) {
      return { allocations: [], error: '有一个项目已不可用，请重新选择' }
    }
  }

  const weights = usable.map((row) =>
    mode === 'ratio' ? Math.round(parseDecimal(row.value) * 100) : 0,
  )
  const amounts =
    mode === 'ratio'
      ? largestRemainder(totalCents, weights)
      : usable.map((row) => Math.round(parseDecimal(row.value) * 100))

  if (mode === 'amount') {
    const sum = amounts.reduce((total, value) => total + value, 0)
    if (sum !== totalCents) {
      return {
        allocations: [],
        error: `分摊合计 ${formatMoney(sum / 100)}，与总额相差 ${formatMoney(
          Math.abs(totalCents - sum) / 100,
        )}`,
      }
    }
  }

  interface MergedTarget {
    targetType: AllocationTarget
    projectId?: string
    amountCents: number
    weight: number
  }

  const merged = new Map<string, MergedTarget>()
  usable.forEach((row, index) => {
    const amountCents = amounts[index] ?? 0
    if (amountCents <= 0) return

    const current = merged.get(row.target)
    if (current) {
      current.amountCents += amountCents
      current.weight += weights[index]
      return
    }

    if (row.target === 'daily') {
      merged.set('daily', {
        targetType: 'daily',
        amountCents,
        weight: weights[index],
      })
      return
    }

    merged.set(row.target, {
      targetType: 'project',
      projectId: row.target.slice('project:'.length),
      amountCents,
      weight: weights[index],
    })
  })

  const allocations: AllocationLine[] = [...merged.values()].map((item) => ({
    id: newAllocationId(),
    targetType: item.targetType,
    ...(item.projectId ? { projectId: item.projectId } : {}),
    amountCents: item.amountCents,
    ...(mode === 'ratio' && item.weight > 0 ? { weight: item.weight } : {}),
    ratioBp: Math.round((item.amountCents / totalCents) * 10000),
    basis: mode === 'ratio' ? 'ratio' : 'fixed',
  }))

  if (allocations.length < 2) {
    return {
      allocations: [],
      error: '分摊金额太小，请调高金额或比例',
    }
  }

  const total = allocations.reduce(
    (sum, line) => sum + line.amountCents,
    0,
  )
  if (total !== totalCents) {
    return { allocations: [], error: '分摊没有对齐总额，请检查金额' }
  }

  return { allocations, error: '' }
}

type RecurringKind = RecurringFrequency['kind']

interface RecurringFormState {
  enabled: boolean
  kind: RecurringKind
  monthlyDay: string
  weeklyDay: string
  yearlyMonth: string
  yearlyDay: string
  intervalDays: string
  startDate: string
  endless: boolean
  endDate: string
  mode: RecurringMode
}

function defaultRecurringForm(
  dateKey: string,
  enabled = false,
): RecurringFormState {
  const day = String(Number(dateKey.slice(8, 10)) || 1)
  const month = String(Number(dateKey.slice(5, 7)) || 1)
  return {
    enabled,
    kind: 'monthly',
    monthlyDay: day,
    weeklyDay: String(weekdayNumber(dateKey)),
    yearlyMonth: month,
    yearlyDay: day,
    intervalDays: '30',
    startDate: dateKey,
    endless: true,
    endDate: '',
    mode: 'auto',
  }
}

function recurringFormFromRule(rule: RecurringRule): RecurringFormState {
  const base = defaultRecurringForm(rule.startDate, true)
  const frequency = rule.frequency
  return {
    ...base,
    enabled: true,
    kind: frequency.kind,
    ...(frequency.kind === 'monthly'
      ? { monthlyDay: String(frequency.day) }
      : {}),
    ...(frequency.kind === 'weekly'
      ? { weeklyDay: String(frequency.weekday) }
      : {}),
    ...(frequency.kind === 'yearly'
      ? {
          yearlyMonth: String(frequency.month),
          yearlyDay: String(frequency.day),
        }
      : {}),
    ...(frequency.kind === 'interval'
      ? { intervalDays: String(frequency.days) }
      : {}),
    startDate: rule.startDate,
    endless: !rule.endDate,
    endDate: rule.endDate ?? '',
    mode: rule.mode,
  }
}

function recurringFrequency(
  form: RecurringFormState,
): RecurringFrequency | null {
  if (form.kind === 'monthly') {
    const day = Number(form.monthlyDay)
    return Number.isInteger(day) && day >= 1 && day <= 31
      ? { kind: 'monthly', day }
      : null
  }
  if (form.kind === 'weekly') {
    const weekday = Number(form.weeklyDay)
    return Number.isInteger(weekday) && weekday >= 0 && weekday <= 6
      ? { kind: 'weekly', weekday }
      : null
  }
  if (form.kind === 'yearly') {
    const month = Number(form.yearlyMonth)
    const day = Number(form.yearlyDay)
    return Number.isInteger(month) &&
      month >= 1 &&
      month <= 12 &&
      Number.isInteger(day) &&
      day >= 1 &&
      day <= 31
      ? { kind: 'yearly', month, day }
      : null
  }
  const days = Number(form.intervalDays)
  return Number.isInteger(days) && days >= 1 && days <= 366
    ? { kind: 'interval', days }
    : null
}

function scopeOfAllocations(allocations: AllocationLine[]): TransactionScope {
  return getScope({ allocations } as LedgerTransaction)
}

